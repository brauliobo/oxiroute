#[test]
fn writes_metadata_as_a_timestamp_zero_script_tag_without_media_flags() {
    let mut muxer = FlvMuxer::new(Cursor::new(Vec::new())).expect("create muxer");
    muxer
        .write_metadata(&[0x02, 0x00, 0x01, b'x'])
        .expect("metadata tag");

    assert_eq!(
        muxer.close().expect("close muxer").into_inner(),
        vec![
            0x46, 0x4c, 0x56, 0x01, 0x00, 0x00, 0x00, 0x00, 0x09, 0x00, 0x00, 0x00, 0x00, 0x12,
            0x00, 0x00, 0x04, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x02, 0x00, 0x01, b'x',
            0x00, 0x00, 0x00, 0x0f,
        ]
    );
}

#[test]
fn writes_audio_only_flv_with_normalized_timestamps() {
    let mut muxer = FlvMuxer::new(Cursor::new(Vec::new())).expect("create muxer");
    muxer
        .write_audio(900, &[0xaf, 0x00, 0x12, 0x10])
        .expect("AAC sequence header");
    muxer
        .write_audio(1_000, &[0xaf, 0x01, 0x11, 0x22])
        .expect("first AAC frame");
    muxer
        .write_audio(1_023, &[0xaf, 0x01, 0x33, 0x44])
        .expect("second AAC frame");

    let output = muxer.close().expect("close muxer").into_inner();
    assert_eq!(
        output,
        vec![
            0x46, 0x4c, 0x56, 0x01, 0x04, 0x00, 0x00, 0x00, 0x09, 0x00, 0x00, 0x00, 0x00,
            // AAC sequence header at timestamp zero, PreviousTagSize = 11 + 4.
            0x08, 0x00, 0x00, 0x04, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xaf, 0x00, 0x12,
            0x10, 0x00, 0x00, 0x00, 0x0f,
            // First media timestamp establishes the segment origin.
            0x08, 0x00, 0x00, 0x04, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xaf, 0x01, 0x11,
            0x22, 0x00, 0x00, 0x00, 0x0f, // 1023 - 1000 = 23 ms.
            0x08, 0x00, 0x00, 0x04, 0x00, 0x00, 0x17, 0x00, 0x00, 0x00, 0x00, 0xaf, 0x01, 0x33,
            0x44, 0x00, 0x00, 0x00, 0x0f,
        ]
    );
}

