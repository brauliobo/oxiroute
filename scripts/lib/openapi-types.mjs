// Renders the component schemas and GET responses of an OpenAPI document as TypeScript declarations. Shared by the
// generators in this directory; a generator only chooses the document, the output path and the naming.

/**
 * @param {object} document OpenAPI document
 * @param {{ generator: string, prefix: string, decimalSchemas?: string[] }} options `prefix` names the response map
 *   (`<prefix>Responses`); `decimalSchemas` are string schemas rendered as `${number}` so that decimal-string counters
 *   stay distinguishable from other strings.
 */
export function renderTypes(document, { generator, prefix, decimalSchemas = [] }) {
  const schemas = document.components?.schemas
  if (!schemas || typeof schemas !== 'object') throw new Error(`OpenAPI document has no component schemas`)
  const decimal = new Set(decimalSchemas)

  const lines = ['/* eslint-disable */', `// Generated by ${generator}. Do not edit by hand.`, '']
  for (const name of Object.keys(schemas).sort()) {
    const rendered = decimal.has(name) ? [`export type ${name} = \`\${number}\``] : renderNamedSchema(name, schemas[name])
    lines.push(...rendered, '')
  }

  const operations = Object.entries(document.paths ?? [])
    .flatMap(([, pathItem]) => {
      const operation = pathItem?.get
      if (!operation?.operationId) return []
      const response = operation.responses?.['200']?.content?.['application/json']?.schema
      if (!response) return []
      return [{ operationId: operation.operationId, response: typeFor(response) }]
    })
    .sort((left, right) => left.operationId.localeCompare(right.operationId))

  lines.push(`export interface ${prefix}Responses {`)
  for (const operation of operations) lines.push(`  ${operation.operationId}: ${operation.response}`)
  lines.push('}', '')
  lines.push(`export type ${prefix}OperationId = keyof ${prefix}Responses`, '')
  lines.push(
    `export type ${prefix}Response<OperationId extends ${prefix}OperationId> = ${prefix}Responses[OperationId]`,
    '',
  )
  return `${lines.join('\n')}\n`
}

function renderNamedSchema(name, schema) {
  if (isInterface(schema)) {
    return [`export interface ${name} {`, ...renderProperties(schema), '}']
  }
  return [`export type ${name} = ${typeFor(schema)}`]
}

function renderProperties(schema) {
  const properties = schema.properties ?? {}
  const required = new Set(schema.required ?? [])
  const result = []

  for (const propertyName of Object.keys(properties).sort()) {
    const optional = required.has(propertyName) ? '' : '?'
    result.push(`  ${propertyKey(propertyName)}${optional}: ${typeFor(properties[propertyName])}`)
  }

  if (schema.additionalProperties && typeof schema.additionalProperties === 'object') {
    result.push(`  [key: string]: ${typeFor(schema.additionalProperties)}`)
  } else if (schema.additionalProperties === true) {
    result.push('  [key: string]: unknown')
  }

  return result
}

function typeFor(schema) {
  if (!schema || typeof schema !== 'object') return 'unknown'
  if (schema.$ref) return schema.$ref.split('/').at(-1)
  if (schema.const !== undefined) return literal(schema.const)
  if (schema.enum) return schema.enum.map(literal).join(' | ')
  if (schema.anyOf || schema.oneOf) {
    const variants = schema.anyOf ?? schema.oneOf
    return unique(variants.map(typeFor)).join(' | ')
  }
  if (schema.allOf) return schema.allOf.map(typeFor).join(' & ')
  if (schema.type === 'array') return `Array<${typeFor(schema.items)}>`
  if (Array.isArray(schema.type)) return unique(schema.type.map((type) => typeFor({ type }))).join(' | ')
  if (schema.type === 'object' || schema.properties || schema.additionalProperties !== undefined) {
    return isInterface(schema) ? inlineObject(schema) : 'Record<string, unknown>'
  }
  if (schema.type === 'integer' || schema.type === 'number') return 'number'
  if (schema.type === 'boolean') return 'boolean'
  if (schema.type === 'null') return 'null'
  if (schema.type === 'string') return 'string'
  return 'unknown'
}

function inlineObject(schema) {
  const properties = schema.properties ?? {}
  const required = new Set(schema.required ?? [])
  const entries = Object.keys(properties).sort().map((propertyName) => {
    const optional = required.has(propertyName) ? '' : '?'
    return `${propertyKey(propertyName)}${optional}: ${typeFor(properties[propertyName])}`
  })
  if (schema.additionalProperties && typeof schema.additionalProperties === 'object') {
    entries.push(`[key: string]: ${typeFor(schema.additionalProperties)}`)
  }
  return `{ ${entries.join('; ')} }`
}

function isInterface(schema) {
  return schema?.type === 'object' || schema?.properties || schema?.additionalProperties !== undefined
}

function propertyKey(name) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name)
}

function literal(value) {
  return JSON.stringify(value)
}

function unique(values) {
  return [...new Set(values)]
}
