#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct SquidCapabilityReport {
    pub registry_version: u32,
    pub product: &'static str,
    pub reference: SquidCapabilityReference,
    pub profile: SquidCapabilityProfile,
    pub target_version: &'static str,
    pub parity: SquidCapabilityStatus,
    pub complete_parity: bool,
    pub families: &'static [SquidCapabilityFamily],
    pub directives: &'static [SquidDirectiveCapability],
}

impl SquidCapabilityReport {
    #[must_use]
    pub fn allows_complete_parity(&self) -> bool {
        self.complete_parity
            && self.families.iter().all(|family| !family.status.is_open())
            && self
                .directives
                .iter()
                .all(|directive| !directive.status.is_open())
    }

    #[must_use]
    pub fn has_open_entries(&self) -> bool {
        self.families.iter().any(|family| family.status.is_open())
            || self
                .directives
                .iter()
                .any(|directive| directive.status.is_open())
    }
}

