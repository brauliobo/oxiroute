#[test]
fn discards_audio_and_interframes_until_first_avc_keyframe() {
    let mut muxer = FlvMuxer::new(Cursor::new(Vec::new())).expect("create muxer");
    muxer
        .write_video(100, &[0x17, 0x00, 0x00, 0x00, 0x00, 0x01])
        .expect("AVC sequence header");
    muxer
        .write_audio(101, &[0xaf, 0x00, 0x12, 0x10])
        .expect("AAC sequence header");
    assert!(matches!(
        muxer.write_video(105, &[0x17, 0x01, 0x00, 0x00, 0x00]),
        Err(FlvMuxerError::MalformedPayload {
            tag_type: FlvTagType::Video
        })
    ));
    muxer
        .write_video(110, &[0x27, 0x01, 0x00, 0x00, 0x00, 0xde])
        .expect("pre-keyframe AVC interframe");
    muxer
        .write_audio(120, &[0xaf, 0x01, 0xad])
        .expect("pre-keyframe AAC frame");
    muxer
        .write_video(130, &[0x17, 0x01, 0x00, 0x00, 0x00, 0xbe])
        .expect("first AVC keyframe");
    muxer
        .write_audio(140, &[0xaf, 0x01, 0xef])
        .expect("post-keyframe AAC frame");

    let output = muxer.close().expect("close muxer").into_inner();
    assert_eq!(
        output,
        vec![
            0x46, 0x4c, 0x56, 0x01, 0x05, 0x00, 0x00, 0x00, 0x09, 0x00, 0x00, 0x00, 0x00, 0x09,
            0x00, 0x00, 0x06, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x17, 0x00, 0x00, 0x00,
            0x00, 0x01, 0x00, 0x00, 0x00, 0x11, 0x08, 0x00, 0x00, 0x04, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x00, 0xaf, 0x00, 0x12, 0x10, 0x00, 0x00, 0x00, 0x0f, 0x09, 0x00, 0x00,
            0x06, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x17, 0x01, 0x00, 0x00, 0x00, 0xbe,
            0x00, 0x00, 0x00, 0x11, 0x08, 0x00, 0x00, 0x03, 0x00, 0x00, 0x0a, 0x00, 0x00, 0x00,
            0x00, 0xaf, 0x01, 0xef, 0x00, 0x00, 0x00, 0x0e,
        ]
    );
    assert!(!output.contains(&0xde));
    assert!(!output.contains(&0xad));
}

