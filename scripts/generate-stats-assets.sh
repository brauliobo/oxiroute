#!/usr/bin/env bash
# Installs a built stats page bundle as crates/oxiroute-server/assets/stats and regenerates the
# include_bytes! table that embeds it, so `cargo build` needs no node.
#
#   generate-stats-assets.sh                  regenerate the table from the installed assets
#   generate-stats-assets.sh --from DIR       install DIR (ui/dist-stats) first, then regenerate
#   generate-stats-assets.sh [--from DIR] --check   change nothing; fail when the repository differs
#
# DIR holds the shell (index.html, or stats.html which is installed as index.html) and assets/<name>
# files whose names end in a content hash (`app-Bx3k9aZ1.js`): they are served as immutable.
set -euo pipefail

repo_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
assets_dir="${repo_dir}/crates/oxiroute-server/assets/stats"
table="${repo_dir}/crates/oxiroute-server/src/observability/stats_page/assets/table.rs"
source_dir=${assets_dir}
check=false

while (($# > 0)); do
  case "$1" in
    --from)
      source_dir=${2:?--from needs a directory}
      shift
      ;;
    --check) check=true ;;
    *)
      printf 'usage: %s [--from DIR] [--check]\n' "${BASH_SOURCE[0]}" >&2
      exit 2
      ;;
  esac
  shift
done

fail() {
  printf 'generate-stats-assets: %s\n' "$*" >&2
  exit 1
}

work=$(mktemp -d)
trap 'rm -rf -- "${work}"' EXIT
stage="${work}/stats"
mkdir -p -- "${stage}/assets"

shell_source="${source_dir}/index.html"
[[ -f "${shell_source}" ]] || shell_source="${source_dir}/stats.html"
[[ -f "${shell_source}" ]] || fail "${source_dir} has neither index.html nor stats.html"
cp -- "${shell_source}" "${stage}/index.html"
if [[ -d "${source_dir}/assets" ]]; then
  find "${source_dir}/assets" -mindepth 1 -maxdepth 1 -exec cp -r -- {} "${stage}/assets/" \;
fi

grep -q '/__stats_prefix__' "${stage}/index.html" ||
  fail 'the shell has no /__stats_prefix__ token: build with vite base "/__stats_prefix__/"'
! grep -Eq '(src|href)="/assets/' "${stage}/index.html" ||
  fail 'the shell links /assets/ directly instead of through /__stats_prefix__'

hashed='^.+-[A-Za-z0-9_-]{8,}\.(js|css|svg|png|ico|woff2)$'
while IFS= read -r -d '' entry; do
  name=${entry#"${stage}/assets/"}
  [[ -f "${entry}" && ! -L "${entry}" && "${name}" =~ ${hashed} ]] ||
    fail "assets/${name} must be a regular file named <name>-<hash>.<js|css|svg|png|ico|woff2>"
done < <(find "${stage}/assets" -mindepth 1 -print0)

generated="${work}/table.rs"
{
  printf '// @generated by scripts/generate-stats-assets.sh from crates/oxiroute-server/assets/stats.\n'
  printf '// Do not edit: regenerate it after changing the assets.\n\n'
  printf 'use super::Asset;\n\n'
  printf 'pub(super) const SHELL: &str = include_str!("../../../../assets/stats/index.html");\n\n'
  printf 'pub(super) static ASSETS: &[Asset] = &[\n'
  while IFS= read -r -d '' entry; do
    name=${entry#"${stage}/assets/"}
    digest=$(sha256sum -- "${entry}" | cut -c1-32)
    printf '    Asset {\n        name: "%s",\n        etag: "\\"%s\\"",\n' "${name}" "${digest}"
    printf '        body: include_bytes!("../../../../assets/stats/assets/%s"),\n    },\n' "${name}"
  done < <(find "${stage}/assets" -mindepth 1 -print0 | LC_ALL=C sort -z)
  printf '];\n'
} >"${generated}"

if [[ "${check}" == true ]]; then
  diff -r -- "${stage}" "${assets_dir}" >&2 || fail "${assets_dir} differs from ${source_dir}"
  cmp -s -- "${generated}" "${table}" || fail "${table#"${repo_dir}/"} is stale: regenerate it"
  printf 'stats assets: embedded table and assets match %s\n' "${source_dir#"${repo_dir}/"}"
  exit 0
fi

if [[ "${source_dir}" != "${assets_dir}" ]]; then
  rm -rf -- "${assets_dir}"
  mkdir -p -- "$(dirname -- "${assets_dir}")"
  cp -r -- "${stage}" "${assets_dir}"
fi
mkdir -p -- "$(dirname -- "${table}")"
cp -- "${generated}" "${table}"
printf 'stats assets: installed %s and regenerated %s\n' \
  "${assets_dir#"${repo_dir}/"}" "${table#"${repo_dir}/"}"
