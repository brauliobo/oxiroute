/// Returns the immutable target-version Squid capability registry.
#[must_use]
pub const fn squid_capability_report() -> SquidCapabilityReport {
    SquidCapabilityReport {
        registry_version: SQUID_CAPABILITY_REGISTRY_VERSION,
        product: "squid",
        reference: SquidCapabilityReference {
            kind: "git_checkout",
            value: SQUID_TARGET_VERSION,
            documentation: "docs/UPSTREAM_ANALYSIS.md",
        },
        profile: SquidCapabilityProfile {
            id: SQUID_CAPABILITY_PROFILE_ID,
            version: SQUID_CAPABILITY_PROFILE_VERSION,
        },
        target_version: SQUID_TARGET_VERSION,
        parity: SquidCapabilityStatus::Partial,
        complete_parity: false,
        families: FAMILIES,
        directives: DIRECTIVES,
    }
}

/// Finds every registered form for a native directive key.
pub fn squid_directive_capabilities(
    key: &str,
) -> impl Iterator<Item = &'static SquidDirectiveCapability> {
    DIRECTIVES
        .iter()
        .filter(move |directive| directive.key == key)
}
