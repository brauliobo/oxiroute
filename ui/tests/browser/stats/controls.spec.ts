import { expect, test } from '@playwright/test'

import { PAGE, serveStats } from './support'

// Desktop and mobile projects both run this file (playwright.config.ts).
test.describe('stats page controls', () => {
  test('pauses and resumes the refresh', async ({ page }) => {
    const served = await serveStats(page)
    await page.goto(`${PAGE}?interval=1000`)
    const state = page.getByRole('status').first()
    await expect(state).toHaveAttribute('data-status', 'live')
    await page.getByRole('button', { name: 'Pause' }).click()
    await expect(state).toHaveAttribute('data-status', 'paused')
    await expect(page).toHaveURL(/paused=1/)
    const paused = served.snapshots()
    await page.waitForTimeout(2500)
    expect(served.snapshots()).toBe(paused)
    await page.getByRole('button', { name: 'Resume' }).click()
    await expect(state).toHaveAttribute('data-status', 'live')
    await expect.poll(() => served.snapshots()).toBeGreaterThan(paused)
    await expect(page).not.toHaveURL(/paused/)
  })

  test('refreshes once on request while paused', async ({ page }) => {
    const served = await serveStats(page)
    await page.goto(`${PAGE}?paused=1`)
    await expect(page.getByRole('button', { name: 'Resume' })).toBeVisible()
    await expect.poll(() => served.snapshots()).toBe(1)
    await page.getByRole('button', { name: 'Refresh now' }).click()
    await expect.poll(() => served.snapshots()).toBe(2)
  })

  test('restores the view from the URL, keeps it across a reload and writes changes back', async ({ page }) => {
    await serveStats(page)
    await page.goto(`${PAGE}?q=origin&state=up,down&problems=1&sort=-rate&interval=5000&theme=dark`)
    const restored = async () => {
      await expect(page.getByRole('searchbox', { name: 'Search' })).toHaveValue('origin')
      await expect(page.getByRole('button', { name: 'UP', exact: true })).toHaveAttribute('aria-pressed', 'true')
      await expect(page.getByRole('button', { name: 'DRAIN', exact: true })).toHaveAttribute('aria-pressed', 'false')
      await expect(page.getByRole('button', { name: 'Problems only' })).toHaveAttribute('aria-pressed', 'true')
      await expect(page.getByLabel('Sort by')).toHaveValue('rate')
      await expect(page.getByRole('button', { name: 'Descending' })).toHaveAttribute('aria-pressed', 'true')
      await expect(page.getByLabel('Refresh every')).toHaveValue('5000')
      await expect(page.getByLabel('Theme')).toHaveValue('dark')
    }
    await restored()
    await page.reload()
    await restored()
    await page.getByRole('searchbox', { name: 'Search' }).fill('api')
    await page.getByRole('button', { name: 'Problems only' }).click()
    const url = new URL(page.url())
    expect(url.searchParams.get('q')).toBe('api')
    expect(url.searchParams.has('problems')).toBe(false)
    expect(url.searchParams.get('sort')).toBe('-rate')
  })

  test('"/" focuses the search box, Escape clears it, "?" opens the help and gives focus back', async ({ page }) => {
    await serveStats(page)
    await page.goto(PAGE)
    await expect(page.getByRole('status').first()).toHaveAttribute('data-status', 'live')
    await page.keyboard.press('/')
    const search = page.getByRole('searchbox', { name: 'Search' })
    await expect(search).toBeFocused()
    await expect(search).toHaveValue('')
    await page.keyboard.type('p/p')
    await expect(search).toHaveValue('p/p')
    await expect(page).toHaveURL(/q=p%2Fp/)
    await page.keyboard.press('Escape')
    await expect(search).toHaveValue('')
    await search.blur()

    await page.getByRole('button', { name: 'Keyboard shortcuts (?)' }).focus()
    await page.keyboard.press('Shift+?')
    const help = page.getByRole('dialog', { name: 'Keyboard shortcuts' })
    await expect(help).toBeVisible()
    await expect(help.getByRole('button', { name: 'Close' })).toBeFocused()
    for (const key of ['/', '?', 'p', 'r', 't', 'f', 'Esc']) await expect(help.locator('kbd', { hasText: new RegExp(`^${key.replace('?', '\\?')}$`) })).toBeVisible()
    await page.keyboard.press('p')
    await expect(page).not.toHaveURL(/paused/)
    await page.keyboard.press('Escape')
    await expect(help).toBeHidden()
    await expect(page.getByRole('button', { name: 'Keyboard shortcuts (?)' })).toBeFocused()
  })

  test('keyboard shortcuts p, f and t change the view', async ({ page }) => {
    await serveStats(page)
    await page.goto(PAGE)
    await expect(page.getByRole('status').first()).toHaveAttribute('data-status', 'live')
    await page.keyboard.press('p')
    await page.keyboard.press('f')
    await page.keyboard.press('t')
    await expect(page).toHaveURL(/\?problems=1&paused=1&theme=light$/)
  })

  test('is reachable by keyboard from the skip link to the footer with a visible focus ring', async ({ page }) => {
    await serveStats(page)
    await page.goto(PAGE)
    await page.keyboard.press('Tab')
    const skip = page.getByRole('link', { name: 'Skip to statistics' })
    await expect(skip).toBeFocused()
    expect(await skip.evaluate((element) => getComputedStyle(element).outlineStyle)).not.toBe('none')
    await page.keyboard.press('Enter')
    await expect(page.locator('#ox-main')).toBeFocused()
    for (const name of ['CSV', 'JSON']) await expect(page.getByRole('link', { name })).toBeVisible()
    await expect(page.getByRole('link', { name: 'CSV' })).toHaveAttribute('href', `${PAGE}/stats.csv`)
    await expect(page.getByRole('link', { name: 'JSON' })).toHaveAttribute('href', `${PAGE}/snapshot.json`)
  })

  test('has the landmarks and does not overflow the viewport', async ({ page }) => {
    await serveStats(page)
    await page.goto(PAGE)
    await expect(page.getByRole('banner')).toBeVisible()
    await expect(page.getByRole('search', { name: 'Filter and view' })).toBeVisible()
    await expect(page.getByRole('main')).toBeVisible()
    await expect(page.getByRole('contentinfo')).toBeVisible()
    await expect(page.getByRole('heading', { level: 1, name: 'OxiRoute statistics' })).toBeVisible()
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)
    expect(overflow).toBeLessThanOrEqual(0)
    const small = await page.getByRole('button', { name: 'Pause' }).boundingBox()
    expect(small!.height).toBeGreaterThanOrEqual(page.viewportSize()!.width < 720 ? 40 : 28)
  })

  test('prints the data without the controls', async ({ page }) => {
    await serveStats(page)
    await page.goto(PAGE)
    await expect(page.getByRole('search')).toBeVisible()
    await page.emulateMedia({ media: 'print' })
    await expect(page.getByRole('search')).toBeHidden()
    await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
  })
})
