#[test]
fn late_avc_sequence_header_rearms_keyframe_gating() {
    let mut muxer = FlvMuxer::new(Cursor::new(Vec::new())).expect("create muxer");
    muxer
        .write_audio(100, &[0x2f, 0x11])
        .expect("initial MP3 frame");
    muxer
        .write_video(110, &[0x17, 0x00, 0x00, 0x00, 0x00, 0x01])
        .expect("late AVC sequence header");
    muxer
        .write_audio(120, &[0x2f, 0x22])
        .expect("gated MP3 frame");
    muxer
        .write_video(125, &[0x27, 0x01, 0x00, 0x00, 0x00, 0x33])
        .expect("gated AVC interframe");
    muxer
        .write_video(130, &[0x17, 0x01, 0x00, 0x00, 0x00, 0x44])
        .expect("subsequent AVC keyframe");
    muxer
        .write_audio(140, &[0x2f, 0x55])
        .expect("released MP3 frame");

    let output = muxer.close().expect("close muxer").into_inner();
    assert_eq!(
        output,
        vec![
            0x46, 0x4c, 0x56, 0x01, 0x05, 0x00, 0x00, 0x00, 0x09, 0x00, 0x00, 0x00, 0x00, 0x08,
            0x00, 0x00, 0x02, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x2f, 0x11, 0x00, 0x00,
            0x00, 0x0d, 0x09, 0x00, 0x00, 0x06, 0x00, 0x00, 0x0a, 0x00, 0x00, 0x00, 0x00, 0x17,
            0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x11, 0x09, 0x00, 0x00, 0x06, 0x00,
            0x00, 0x1e, 0x00, 0x00, 0x00, 0x00, 0x17, 0x01, 0x00, 0x00, 0x00, 0x44, 0x00, 0x00,
            0x00, 0x11, 0x08, 0x00, 0x00, 0x02, 0x00, 0x00, 0x28, 0x00, 0x00, 0x00, 0x00, 0x2f,
            0x55, 0x00, 0x00, 0x00, 0x0d,
        ]
    );
    assert!(!output.contains(&0x22));
    assert!(!output.contains(&0x33));
}

#[test]
fn clamps_timestamp_regression_but_preserves_u32_wraparound() {
    let mut regressing = FlvMuxer::new(Cursor::new(Vec::new())).expect("create muxer");
    regressing
        .write_audio(1_000, &[0x2f, 0xaa])
        .expect("first MP3 frame");
    regressing
        .write_audio(900, &[0x2f, 0xbb])
        .expect("regressing MP3 frame");
    let regressing = regressing.close().expect("close muxer").into_inner();
    assert_eq!(tag_timestamp(&regressing, 13), 0);
    assert_eq!(tag_timestamp(&regressing, 30), 0);

    let mut wrapping = FlvMuxer::new(Cursor::new(Vec::new())).expect("create muxer");
    wrapping
        .write_audio(0xffff_fff0, &[0x2f, 0xaa])
        .expect("first MP3 frame");
    wrapping
        .write_audio(0x0000_0010, &[0x2f, 0xbb])
        .expect("wrapped MP3 frame");
    let wrapping = wrapping.close().expect("close muxer").into_inner();
    assert_eq!(tag_timestamp(&wrapping, 13), 0);
    assert_eq!(tag_timestamp(&wrapping, 30), 32);
}

#[test]
fn rejects_codec_headers_above_the_cache_bound_without_accepting_them() {
    let mut audio_config = vec![0; MAX_CACHED_CODEC_HEADER_SIZE + 1];
    audio_config[0] = 0xaf;
    let mut audio = FlvMuxer::new(Cursor::new(Vec::new())).expect("create audio muxer");
    assert!(matches!(
        audio.write_audio(0, &audio_config),
        Err(FlvMuxerError::CodecHeaderTooLarge {
            tag_type: FlvTagType::Audio,
            size
        }) if size == MAX_CACHED_CODEC_HEADER_SIZE + 1
    ));
    audio
        .write_audio(1, &[0xaf, 0x01, 0xaa])
        .expect("AAC remains gated");

    let mut video_configuration = vec![0; MAX_CACHED_CODEC_HEADER_SIZE + 1];
    video_configuration[0] = 0x17;
    let mut video = FlvMuxer::new(Cursor::new(Vec::new())).expect("create video muxer");
    assert!(matches!(
        video.write_video(0, &video_configuration),
        Err(FlvMuxerError::CodecHeaderTooLarge {
            tag_type: FlvTagType::Video,
            size
        }) if size == MAX_CACHED_CODEC_HEADER_SIZE + 1
    ));
    video
        .write_video(1, &[0x17, 0x01, 0x00, 0x00, 0x00, 0xaa])
        .expect("AVC remains gated");

    let empty_flv = vec![
        0x46, 0x4c, 0x56, 0x01, 0x00, 0x00, 0x00, 0x00, 0x09, 0x00, 0x00, 0x00, 0x00,
    ];
    assert_eq!(
        audio.close().expect("close audio muxer").into_inner(),
        empty_flv
    );
    assert_eq!(
        video.close().expect("close video muxer").into_inner(),
        empty_flv
    );
}

#[test]
fn writes_all_three_data_size_bytes() {
    let payload = vec![0x2f; 0x0001_0203];
    let mut muxer = FlvMuxer::new(Cursor::new(Vec::new())).expect("create muxer");
    muxer
        .write_audio(0, &payload)
        .expect("large but representable audio tag");

    let output = muxer.close().expect("close muxer").into_inner();
    assert_eq!(&output[14..17], &[0x01, 0x02, 0x03]);
    assert_eq!(&output[24..24 + payload.len()], payload);
    assert_eq!(&output[24 + payload.len()..], &[0x00, 0x01, 0x02, 0x0e]);
}

#[test]
fn rejects_malformed_and_oversized_payloads_without_writing_tags() {
    let mut muxer = FlvMuxer::new(Cursor::new(Vec::new())).expect("create muxer");

    assert!(matches!(
        muxer.write_audio(0, &[]),
        Err(FlvMuxerError::MalformedPayload {
            tag_type: FlvTagType::Audio
        })
    ));
    assert!(matches!(
        muxer.write_audio(0, &[0xaf]),
        Err(FlvMuxerError::MalformedPayload {
            tag_type: FlvTagType::Audio
        })
    ));
    assert!(matches!(
        muxer.write_audio(0, &[0xaf, 0x02]),
        Err(FlvMuxerError::MalformedPayload {
            tag_type: FlvTagType::Audio
        })
    ));
    assert!(matches!(
        muxer.write_audio(0, &[0xaf, 0x00]),
        Err(FlvMuxerError::MalformedPayload {
            tag_type: FlvTagType::Audio
        })
    ));
    assert!(matches!(
        muxer.write_video(0, &[0x17, 0x01]),
        Err(FlvMuxerError::MalformedPayload {
            tag_type: FlvTagType::Video
        })
    ));
    assert!(matches!(
        muxer.write_video(0, &[0x17, 0x00, 0x00, 0x00, 0x00]),
        Err(FlvMuxerError::MalformedPayload {
            tag_type: FlvTagType::Video
        })
    ));
    assert!(matches!(
        muxer.write_video(0, &[0x17, 0x01, 0x00, 0x00, 0x00]),
        Err(FlvMuxerError::MalformedPayload {
            tag_type: FlvTagType::Video
        })
    ));
    assert!(matches!(
        muxer.write_video(0, &[0x07]),
        Err(FlvMuxerError::MalformedPayload {
            tag_type: FlvTagType::Video
        })
    ));

    let oversized = vec![0x2f; MAX_FLV_TAG_DATA_SIZE + 1];
    assert!(matches!(
        muxer.write_audio(0, &oversized),
        Err(FlvMuxerError::PayloadTooLarge {
            tag_type: FlvTagType::Audio,
            size
        }) if size == MAX_FLV_TAG_DATA_SIZE + 1
    ));
    muxer
        .write_audio(0, &[0xaf, 0x01, 0xaa])
        .expect("malformed AAC header did not release raw media");
    muxer
        .write_video(0, &[0x17, 0x01, 0x00, 0x00, 0x00, 0xaa])
        .expect("malformed AVC header did not release keyframes");

    assert_eq!(
        muxer.close().expect("close muxer").into_inner(),
        vec![
            0x46, 0x4c, 0x56, 0x01, 0x00, 0x00, 0x00, 0x00, 0x09, 0x00, 0x00, 0x00, 0x00,
        ]
    );
}

fn tag_timestamp(output: &[u8], tag_start: usize) -> u32 {
    u32::from_be_bytes([
        output[tag_start + 7],
        output[tag_start + 4],
        output[tag_start + 5],
        output[tag_start + 6],
    ])
}
